#!/usr/bin/env python3
"""Generate user-local pkg-config profiles for Fedora's serial OpenBLAS."""

import argparse
import ctypes
import re
import shlex
import subprocess
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path,
                        default=Path.home() / '.local/lib/pkgconfig')
    parser.add_argument('--force', action='store_true',
                        help='replace existing profiles in the output directory')
    args = parser.parse_args()
    # Use RPM's architecture-specific paths, rather than assuming x86_64.
    libdir = Path(subprocess.check_output(
        ['rpm', '--eval', '%{_libdir}'], text=True).strip())
    includedir = Path('/usr/include/openblas')
    if not (includedir / 'cblas.h').is_file():
        parser.error('missing headers; install openblas-devel')

    print('Static linking also requires gcc-gfortran (provides the libgfortran linker library).')
    profiles = {}
    for name, ilp64 in [('openblas', False), ('openblas64', True)]:
        shared = libdir / f'lib{name}.so'
        if not shared.is_file():
            parser.error(f'missing {shared}; install openblas-devel and matching runtime packages')
        lib = ctypes.CDLL(str(shared))
        lib.openblas_get_config.restype = ctypes.c_char_p
        config = lib.openblas_get_config().decode()
        version = re.search(r'OpenBLAS\s+(\S+)', config)
        if version is None or ('USE64BITINT' in config) != ilp64:
            parser.error(f'unexpected ABI/version for {shared}: {config}')
        if lib.openblas_get_parallel() != 0:
            parser.error(f'{shared} is not the expected serial Fedora build')
        # Escape whitespace for pkg-config's shell-style flag syntax.
        inc = str(includedir).replace(' ', r'\ ')
        flags = f'-I{inc}' + (' -DOPENBLAS_USE64BITINT' if ilp64 else '')
        profiles[name] = f'''# Generated by fedora-openblas-pc.py; serial, unsuffixed CBLAS symbols.
libdir={libdir}
includedir={includedir}

Name: {name}
Description: Fedora serial OpenBLAS ({'ILP64' if ilp64 else 'LP64'})
Version: {version.group(1)}
Libs: -L${{libdir}} -l{name}
Libs.private: -lgfortran -lm -lpthread
Cflags: {flags}
'''
        if not (libdir / f'lib{name}.a').is_file():
            print(f'Note: {name} supports dynamic linking here; install openblas-static for static linking.')

    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name in profiles:
        target = args.output_dir / f'{name}.pc'
        if target.exists() and not args.force:
            parser.error(f'{target} exists; use --force to replace it')
    for name, content in profiles.items():
        target = args.output_dir / f'{name}.pc'
        target.write_text(content)
        print(f'Wrote {target}')
    print('\nUse these profiles in the current shell:')
    print('export PKG_CONFIG_PATH=' + shlex.quote(str(args.output_dir.resolve()))
          + '${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}')


if __name__ == '__main__':
    main()
